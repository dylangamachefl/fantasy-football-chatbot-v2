import json
import os
import dspy
from dspy.teleprompt import BootstrapFewShot
from src.agent.dspy_modules import SQLGeneratorModule
from src.agent.dspy_signatures import SQLGeneratorSignature
from src.config.llm_config import LLM_API_KEY, LLM_API_BASE_URL, LLM_MODEL_NAME, LLM_PROVIDER

# --- 1. Setup DSPy ---
def init_dspy():
    # Similar to dspy_config.py but simplified for this script
    if not LLM_API_KEY:
        raise ValueError("LLM_API_KEY not found. Ensure environment variables are set.")

    dspy_model_name = f"openai/{LLM_MODEL_NAME}"
    print(f"Initializing DSPy with model={dspy_model_name}")

    lm = dspy.LM(
        model=dspy_model_name,
        api_key=LLM_API_KEY,
        api_base=LLM_API_BASE_URL,
        temperature=0
    )
    dspy.settings.configure(lm=lm)

# --- 2. Load Data ---
def load_dataset():
    data_path = os.path.join(os.path.dirname(__file__), '../../original-backend/data/golden_dataset.json')
    if not os.path.exists(data_path):
        # Fallback for dev environment path differences
        data_path = 'suite/original-backend/data/golden_dataset.json'

    with open(data_path, 'r') as f:
        raw_data = json.load(f)

    # Convert to DSPy Examples
    # Note: SQLGeneratorSignature takes (question, db_schema, previous_sql, error_message)
    # We will assume previous_sql and error_message are empty for training examples.
    examples = []

    # Load Schema to inject into inputs
    schema_str = load_schema_string()

    for item in raw_data:
        # Input: question, schema
        # Output: sql_query, thought (implicitly generated by CoT)
        ex = dspy.Example(
            question=item['question'],
            db_schema=schema_str,
            previous_sql="",
            error_message="",
            sql_query=item['sql']
        ).with_inputs('question', 'db_schema', 'previous_sql', 'error_message')
        examples.append(ex)

    return examples

def load_schema_string():
    # Load from the frontend asset to ensure consistency
    schema_path = os.path.join(os.path.dirname(__file__), '../../apps/chat-app/public/assets/schema.json')
    if not os.path.exists(schema_path):
        schema_path = 'apps/chat-app/public/assets/schema.json'

    with open(schema_path, 'r') as f:
        schema_data = json.load(f)

    # Reconstruct the string format used in apps/chat-app/src/lib/agent.ts
    # (Simplified reproduction of the logic)

    # Note: The agent dynamically filters tables. For optimization, we probably want
    # to provide the FULL schema or at least a consistent large subset, so the model learns
    # to handle the structure. Since we don't have the "router" logic here, we'll
    # just dump the core structure or the whole thing.
    # Let's dump the whole thing to be robust.

    filtered_schema_parts = ["==================================================", "DATABASE SCHEMA", "=================================================="]

    for table_name, info in schema_data.items():
        filtered_schema_parts.append(f"\n📄 TABLE: {table_name}")
        filtered_schema_parts.append(f"   Description: {info['description']}")
        filtered_schema_parts.append(f"   Columns:")
        for col in info['columns']:
            filtered_schema_parts.append(f"  - {col['name']}: {col['description']}")

    filtered_schema_parts.append("\n==================================================")
    return '\n'.join(filtered_schema_parts)

# --- 3. Define Metric ---
def validate_sql(example, pred, trace=None):
    # exact match on SQL
    # Normalize whitespace
    gold_sql = " ".join(example.sql_query.split())
    pred_sql = " ".join(pred.sql_query.split())
    return gold_sql == pred_sql

# --- 4. Main Optimization ---
def optimize():
    init_dspy()
    trainset = load_dataset()

    # We don't have a huge dataset, so we'll use all of it for training for now,
    # or split if we had more.

    print(f"Loaded {len(trainset)} examples.")

    # Define the module
    module = SQLGeneratorModule()

    # Compile
    # metric=validate_sql might be too strict if the model generates valid but slightly different SQL.
    # But for a golden dataset, we might want exact alignment.
    teleprompter = BootstrapFewShot(metric=validate_sql, max_bootstrapped_demos=4, max_labeled_demos=4)

    print("Starting optimization...")
    compiled_program = teleprompter.compile(module, trainset=trainset)

    # Save
    output_path = os.path.join(os.path.dirname(__file__), '../../original-backend/data/compiled_sql_generator.json')
    if not os.path.exists(os.path.dirname(output_path)):
         output_path = 'suite/original-backend/data/compiled_sql_generator.json'

    compiled_program.save(output_path)
    print(f"Optimization complete. Saved to {output_path}")

if __name__ == "__main__":
    # Add src to path to allow imports
    import sys
    sys.path.append(os.path.join(os.path.dirname(__file__), '../../original-backend'))

    optimize()
